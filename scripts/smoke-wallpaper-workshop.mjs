// Actual workshop, Home and media components + production registry/settings over isolated Electron IPC.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { once } from "node:events";
import { spawn } from "node:child_process";
import { mkdtemp, mkdir, rm, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { electronSmokeLaunchBlockReason } from "./lib/electron-smoke-launch-guard.mjs";
const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(repo, "package.json"));
const electron = require("electron");
if (typeof electron === "string") {
  const reason = electronSmokeLaunchBlockReason(process.platform, process.env);
  if (reason) throw new Error(reason);
  const temporary = await mkdtemp(join(tmpdir(), "ct-workshop-"));
  try {
    const { build } = await import("vite"); const { default: react } = await import("@vitejs/plugin-react");
    await build({ configFile: false, root: join(repo, "tests/fixtures/wallpaper-workshop-renderer"), base: "./", plugins: [react()], logLevel: "error", build: { outDir: join(temporary, "renderer"), emptyOutDir: true, target: "esnext", assetsInlineLimit: 0 } });
    const { build: bundle } = await import("esbuild");
    await bundle({ entryPoints: [join(repo, "tests/fixtures/wallpaper-workshop-renderer/services.ts")], bundle: true, platform: "node", format: "cjs", outfile: join(temporary, "services.cjs"), logLevel: "error" });
    const environment = { ...process.env }; delete environment.ELECTRON_RUN_AS_NODE;
    const output = resolve(process.argv[2] || join(repo, "../wallpaper-workshop-smoke")); await mkdir(output, { recursive: true });
    const child = spawn(electron, [fileURLToPath(import.meta.url), "--probe", temporary, output, process.argv[3] || "", `--user-data-dir=${join(temporary, "profile")}`], { env: environment, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = ""; child.stdout.on("data", bytes => { stdout += bytes; process.stdout.write(bytes); }); child.stderr.on("data", bytes => process.stderr.write(bytes));
    const timer = setTimeout(() => child.kill("SIGKILL"), 55_000);
    try { const code = await new Promise((resolve, reject) => { child.once("exit", resolve); child.once("error", reject); }); assert.equal(code, 0); assert.match(stdout, /WALLPAPER_WORKSHOP_OK/); }
    finally { clearTimeout(timer); }
  } finally { await rm(temporary, { recursive: true, force: true }); }
} else void probe();
async function probe() {
  const { app, BrowserWindow, ipcMain } = electron;
  try {
    await app.whenReady();
    const index = process.argv.indexOf("--probe"), [temporary, output, packagePath] = process.argv.slice(index + 1);
    const { WallpaperRegistry, SettingsStore, readWindowState, observeWindowState } = require(join(temporary, "services.cjs"));
    const profile = join(temporary, "fixture-data");
    let library = new WallpaperRegistry(profile), settings = new SettingsStore(profile, "ru");
    await library.initialize(); await settings.load();
    const window = new BrowserWindow({ width: 1180, height: 1000, show: false, webPreferences: { backgroundThrottling: false, contextIsolation: true, sandbox: true, preload: join(repo, "tests/fixtures/wallpaper-workshop-renderer/preload.cjs") } });
    for (const [channel, fn] of Object.entries({ "wallpapers:list": () => library.list(), "wallpapers:install": request => library.install(request), "wallpapers:read": id => library.read(id), "wallpapers:export": id => library.export(id), "wallpapers:remove": id => library.remove(id), "settings:get": () => settings.get(), "settings:update": patch => settings.update(patch), "probe:window-get": () => readWindowState(window) })) ipcMain.handle(channel, (_event, value) => fn(value));
    let clipboard = ""; ipcMain.on("probe:clipboard", (_event, value) => { clipboard = value; });
    let unsubscribe = library.onChanged(() => window.webContents.send("wallpapers:changed"));
    const stopWindow = observeWindowState(window, state => window.webContents.send("probe:window-state", state));
    const errors = []; window.webContents.on("console-message", (_event, level, message) => { if (level >= 3) errors.push(message); });
    const run = source => window.webContents.executeJavaScript(source);
    const reload = async () => {
      const loaded = once(window.webContents, "did-finish-load");
      window.reload();
      await loaded;
    };
    const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
    const until = async (predicate, message) => { for (let i = 0; i < 150; i++) { if (await predicate()) return; await delay(40); } throw new Error(message); };
    const click = async text => { await until(() => run(`Boolean([...document.querySelectorAll("button")].find(e => e.textContent === ${JSON.stringify(text)} && !e.disabled))`), `Button stayed disabled: ${text}`); await run(`window.wallpaperProbe.button(${JSON.stringify(text)})`); await delay(50); };
    const select = async (label, value) => { await run(`window.wallpaperProbe.select(${JSON.stringify(label)}, ${JSON.stringify(value)})`); await delay(50); };
    await window.loadFile(join(temporary, "renderer/index.html")); window.showInactive();
    await until(() => run("Boolean(window.wallpaperProbe && document.querySelector('.wallpaper-workshop input[type=file]'))"), "Workshop did not mount");
    if (packagePath) {
      const packageText = await readFile(packagePath, "utf8");
      await run(`(() => { const transfer = new DataTransfer(); transfer.items.add(new File([${JSON.stringify(packageText)}], 'Engine.ctwallpaper')); const input = document.querySelector('.wallpaper-workshop input[type=file]'); input.files = transfer.files; input.dispatchEvent(new Event('change', {bubbles:true})); })()`);
    } else await run("window.wallpaperProbe.import('package')");
    await until(() => run("Boolean(document.querySelector('.wallpaper-workshop__preview img') && !document.querySelector('fieldset').disabled)"), "Package did not decode");
    await select("Предпросмотр", "clock"); await click("Сохранить и применить");
    await until(() => Boolean(settings.get().homeClockWallpaper), "Clock did not save/apply");
    const clockId = settings.get().homeClockWallpaper;
    await click("Старый");
    await until(() => settings.get().homeClockDesign === "classic", "Classic clock did not activate");
    assert.equal(settings.get().homeClockFont, "pixel");
    await until(() => run("Boolean(document.querySelector('#clock [data-skin-media=gif] img') && document.querySelector('#clock svg.clock-pixel-digits'))"), "Clock media/digits missing");
    assert.equal(library.list()[0].recipe.x, 25); assert.equal(library.list()[0].recipe.y, 75); assert.equal(library.list()[0].recipe.dim, .5);
    const rect = await run("(() => {const r = document.querySelector('#clock').getBoundingClientRect(); return { x:Math.round(r.x), y:Math.round(r.y), width:Math.round(r.width), height:Math.round(r.height) };})()");
    const first = (await window.webContents.capturePage(rect)).toBitmap(); let second = first;
    for (let i = 0; i < 20 && first.equals(second); i++) { await delay(125); second = (await window.webContents.capturePage(rect)).toBitmap(); }
    assert.notDeepEqual(first, second, "GIF clock background must move beneath real digits");
    assert.equal(await run("Boolean(document.querySelector('#clock .clock-tile__details'))"), false);
    await click("Новый");
    await until(() => run("Boolean(document.querySelector('#clock .clock-tile__details') && document.querySelector('#clock [data-skin-media=gif] img') && document.querySelector('#clock svg.clock-pixel-digits'))"), "New clock must retain the themed wallpaper and digits");
    await select("Предпросмотр", "avatar"); await click("Сохранить и применить");
    await until(() => settings.get().homeAvatarWallpaper === clockId, "Avatar assignment failed");
    assert.equal(library.list().length, 1, "Reusing saved art must not duplicate it");
    await run("window.wallpaperProbe.import('video')");
    await until(() => run("Boolean(document.querySelector('.wallpaper-workshop__preview video') && !document.querySelector('fieldset').disabled)"), "MP4 did not decode");
    await select("Предпросмотр", "canvas"); await click("Сохранить и применить");
    await until(() => settings.get().canvasBackground.startsWith("wallpaper:"), "Canvas assignment failed");
    await until(() => run("Boolean(document.querySelector('#canvas video')?.readyState >= 2)"), "Canvas video missing");
    assert.equal(await run("document.querySelector('#canvas video').muted && document.querySelector('#canvas video').loop"), true);
    await run("window.wallpaperProbe.showGenerator()"); await click("Сгенерировать PNG");
    await until(() => run("Boolean(document.querySelector('.wallpaper-workshop__preview [data-skin-media=png] img') && !document.querySelector('fieldset').disabled)"), "Pixel generator failed");
    await click("Сохранить в библиотеку"); await until(() => library.list().length === 3, "Generated PNG not saved");
    assert.equal(library.list()[2].media.width, 1920); assert.equal(library.list()[2].media.height, 1080);
    const exported = new Promise((resolve, reject) => window.webContents.session.once("will-download", (_event, item) => {
      item.setSavePath(join(output, "exported.ctwallpaper"));
      item.once("done", (_event, state) => state === "completed" ? resolve() : reject(new Error(`Export download: ${state}`)));
    }));
    await click("Экспорт .ctwallpaper"); await exported;
    const exportedData = JSON.parse(await readFile(join(output, "exported.ctwallpaper"), "utf8"));
    assert.equal(exportedData.kind, "canvastty-wallpaper"); assert.equal(exportedData.source.width, 1920);
    await click("Скопировать задание агенту для этого оформления"); assert.match(clipboard, /LIVE_ENGINE\.md/); assert.match(clipboard, /clockFont/);
    await writeFile(join(output, "wallpaper-workshop.png"), (await window.webContents.capturePage()).toPNG());
    // Simulate a fresh app process: reconstruct services, reload renderer, read only copied profile assets.
    unsubscribe(); library = new WallpaperRegistry(profile); settings = new SettingsStore(profile, "ru");
    await library.initialize(); await settings.load(); unsubscribe = library.onChanged(() => window.webContents.send("wallpapers:changed"));
    await reload();
    await until(() => run("Boolean(document.querySelector('#clock img') && document.querySelector('#avatar img') && document.querySelector('#canvas video')?.readyState >= 2)"), "Saved assets did not return after restart");
    assert.equal(library.list().length, 3); assert.equal(settings.get().homeClockWallpaper, clockId);
    // Direct avatar upload uses the same decode + persistent import path as App.
    await run("document.querySelector('#avatar .mini-media__pick').click()");
    await until(() => library.list().length === 4 && settings.get().homeAvatarWallpaper !== clockId, "Direct GIF avatar did not save");
    const avatarId = settings.get().homeAvatarWallpaper;
    assert.equal(library.list().find(item => item.id === avatarId).media.format, "gif");
    await until(() => run("Boolean(document.querySelector('#avatar [data-skin-media=gif] img'))"), "Direct GIF avatar did not render");
    await run("window.wallpaperProbe.clockBackground()");
    await until(() => settings.get().homeClockWallpaper !== clockId, "Direct clock GIF did not save");
    const directClock = library.list().find(item => item.id === settings.get().homeClockWallpaper);
    assert.equal(directClock.media.format, "gif"); assert.equal(directClock.media.animated, true);
    assert.equal(directClock.recipe.width, 1440); assert.equal(directClock.recipe.height, 810);
    await run("document.querySelector('[aria-label=\"Настроить часы и таймеры\"]').click()");
    await until(() => run("Boolean(document.querySelector('dialog[open]'))"), "Clock editor did not open");
    const input = async (selector, value) => { await run(`window.wallpaperProbe.input(${JSON.stringify(selector)}, ${JSON.stringify(value)})`); await delay(30); };
    await input('.home-time-editor__clock:nth-child(1) input[list]', 'Not/A_Zone');
    await click('Сохранить часы');
    await until(() => run("Boolean(document.querySelector('dialog [role=alert]'))"), 'Invalid zone was not rejected');
    await input('.home-time-editor__clock:nth-child(1) input[list]', 'Europe/Moscow');
    await input('.home-time-editor__clock:nth-child(1) input:not([list])', 'Москва');
    await click('+ Часовой пояс');
    await input('.home-time-editor__clock:nth-child(2) input[list]', 'Asia/Tokyo');
    await input('.home-time-editor__clock:nth-child(2) input:not([list])', 'Токио');
    await input('.home-time-editor__new-timer label:nth-child(1) input', 'Чай');
    await input('.home-time-editor__new-timer label:nth-child(2) input', '0');
    await input('.home-time-editor__new-timer label:nth-child(3) input', '2');
    await click('Добавить таймер');
    await until(() => settings.get().homeTime.timers.length === 1, "First timer not saved");
    await input('.home-time-editor__new-timer label:nth-child(1) input', 'Перерыв');
    await input('.home-time-editor__new-timer label:nth-child(2) input', '10');
    await input('.home-time-editor__new-timer label:nth-child(3) input', '0');
    await click('Добавить таймер');
    await until(() => settings.get().homeTime.timers.length === 2, "Second timer not saved");
    await click('Сохранить часы');
    await until(() => run("document.querySelectorAll('.home-world-clocks article').length === 1 && !document.querySelector('dialog')"), "World clocks did not apply");
    assert.equal(settings.get().homeTime.clocks[0].timeZone, 'Europe/Moscow');
    assert.equal(settings.get().homeTime.clocks[1].timeZone, 'Asia/Tokyo');
    const timerIds = settings.get().homeTime.timers.map(timer => timer.id);
    const control = async label => { await run(`document.querySelector('[aria-label=${JSON.stringify(label)}]').click()`); await delay(80); };
    await control('Запустить Чай');
    await until(() => settings.get().homeTime.timers[0].status === 'running', 'Timer start failed');
    await control('Пауза Чай');
    await until(() => settings.get().homeTime.timers[0].status === 'paused', 'Timer pause failed');
    assert.ok(settings.get().homeTime.timers[0].remainingMs < 2000);
    await control('Запустить Перерыв');
    await control('Запустить Чай');
    await until(() => run(`document.querySelector('[data-timer-id="${timerIds[0]}"]').dataset.timerStatus === 'done'`), 'Countdown did not finish');
    assert.equal(settings.get().homeTime.timers[1].status, 'running', 'Other timer must stay independent');
    await writeFile(join(output, 'home-time.png'), (await window.webContents.capturePage()).toPNG());
    unsubscribe(); library = new WallpaperRegistry(profile); settings = new SettingsStore(profile, 'ru');
    await library.initialize(); await settings.load(); unsubscribe = library.onChanged(() => window.webContents.send('wallpapers:changed'));
    await reload();
    await until(() => run("document.querySelectorAll('.home-timers article').length === 2 && Boolean(document.querySelector('#avatar img'))"), 'Timers/avatar did not restore');
    assert.equal(settings.get().homeAvatarWallpaper, avatarId);
    assert.equal(settings.get().homeTime.clocks.length, 2);
    assert.equal(settings.get().homeTime.timers[1].status, 'running');
    const runningDeadline = settings.get().homeTime.timers[1].endsAt;
    await run("document.querySelector('[aria-label=\"Настроить часы и таймеры\"]').click()");
    await until(() => run("Boolean(document.querySelector('dialog[open]'))"), 'Timer editor did not reopen');
    await click('Чай · 0:02');
    await input('.home-time-editor__new-timer label:nth-child(1) input', 'Чай снова');
    await input('.home-time-editor__new-timer label:nth-child(3) input', '15');
    await click('Сохранить таймер и сбросить отсчёт');
    await until(() => settings.get().homeTime.timers[0].durationMs === 15000, 'Editing timer duration failed');
    assert.equal(settings.get().homeTime.timers[0].status, 'idle');
    assert.equal(settings.get().homeTime.timers[1].endsAt, runningDeadline);
    await control('Закрыть');
    await control('Удалить Чай снова');
    await until(() => settings.get().homeTime.timers.length === 1, 'Removing timer failed');
    assert.equal(settings.get().homeTime.timers[0].endsAt, runningDeadline);
    assert.deepEqual(errors, []);
    const report = { result: "passed", checks: ["actual React workshop and Home components", "actual WallpaperRegistry and SettingsStore via isolated IPC", "portable GIF import and framing recipe", "clock background animates under live pixel digits", "avatar reuse without duplication", "MP4 Canvas wallpaper is silent and looping", "local pixel PNG generator", "saved library reload", "portable file export via native download", "agent prompt parameters", "production media CSP", "direct GIF avatar copies into profile", "direct clock GIF picker persists a landscape recipe", "world-zone editor and persistence", "two independent countdown timers", "timer pause/resume/completion", "timer/avatar profile restart", "invalid time zone rejected", "timer editing and removal preserve other timer"], errors };
    await writeFile(join(output, "verification.json"), JSON.stringify(report, null, 2));
    console.log("WALLPAPER_WORKSHOP_OK " + JSON.stringify(report));
    unsubscribe(); stopWindow(); window.destroy(); app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
}
